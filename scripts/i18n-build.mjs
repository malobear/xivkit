// Pre-renders translated copies of opted-in pages into ja/, de/ and fr/ (ADR 0001).
//
//   pnpm i18n          build ja/ de/ fr/, add hreflang to the English pages and the sitemap
//   pnpm i18n:check    exit 1 if anything the build would write differs from what's on disk
//
// Each copy gets the translated text baked into its static HTML, its own <html lang>,
// canonical, og:url, og:locale, title and description, and a <base href="../"> so every
// relative asset, fetch and link in the page still resolves against the site root.
// i18n.js still runs on top for the parts pages build at runtime.
//
// A language copy is only written when the page is listed in PAGES with that language and
// every translation key it uses exists in that language's JSON. Anything else stays
// English-only, with no hreflang, exactly as before.
//
// The output in ja/, de/ and fr/ is generated: never edit it by hand.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseHTML } from "linkedom";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://xivkit.com/";
const LANGS = ["ja", "de", "fr"];
const OG_LOCALE = { en: "en_US", ja: "ja_JP", de: "de_DE", fr: "fr_FR" };

// Pages that get language copies. `seo` names the i18n `seo.<key>` entry holding the
// translated title and description. `namespaces` lists i18n subtrees the page's own
// scripts read at runtime, which must be complete in a language before it is published.
// Only add a page once its body copy is translated, not just its nav and footer.
const PAGES = [
  { file: "index.html", seo: "index", langs: LANGS },
  { file: "plugins.html", seo: "plugins", langs: LANGS },
  { file: "watchlist.html", seo: "watchlist", langs: LANGS },
  { file: "hunt-for-astronomy.html", seo: "huntForAstronomy", langs: LANGS, namespaces: ["hfa"] },
  { file: "msq-tracker.html", seo: "msqTracker", langs: LANGS, namespaces: ["pages.msqTracker"] },
];

const ALT_START = "<!-- i18n:alternates (generated by scripts/i18n-build.mjs) -->";
const ALT_END = "<!-- /i18n:alternates -->";
const MAP_START = "<!-- i18n:start (generated by scripts/i18n-build.mjs) -->";
const MAP_END = "<!-- i18n:end -->";

const check = process.argv.includes("--check");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const dicts = Object.fromEntries(["en", ...LANGS].map((l) => [l, JSON.parse(read(`i18n/${l}.json`))]));

// ---------- translation lookup (mirrors what i18n.js gets from i18next) ----------

function lookup(dict, key) {
  return key.split(".").reduce((o, k) => (o && typeof o === "object" ? o[k] : undefined), dict);
}
function t(lang, key, vars = {}) {
  let v = lookup(dicts[lang], key);
  if (typeof v !== "string") v = lookup(dicts.en, key);
  if (typeof v !== "string") return key;
  return v.replace(/\{\{\s*(\w+)\s*\}\}/g, (_, k) => (k in vars ? String(vars[k]) : ""));
}
function leafKeys(obj, prefix) {
  if (typeof obj === "string") return [prefix];
  if (!obj || typeof obj !== "object") return [];
  return Object.entries(obj).flatMap(([k, v]) => leafKeys(v, prefix ? `${prefix}.${k}` : k));
}

// ---------- URLs ----------

const enPath = (file) => (file === "index.html" ? "" : file);
const langPath = (lang, file) => `${lang}/${enPath(file)}`;
const urlFor = (lang, file) => SITE + (lang === "en" ? enPath(file) : langPath(lang, file));

// ---------- coverage gate ----------

function keysUsed(document) {
  const keys = new Set();
  document.querySelectorAll("[data-i18n]").forEach((el) => keys.add(el.getAttribute("data-i18n")));
  document.querySelectorAll("[data-i18n-rich]").forEach((el) => keys.add(el.getAttribute("data-i18n-rich")));
  if (document.querySelector("[data-updated]")) {
    keys.add("shared.updated.withPatch");
    keys.add("shared.updated.dateOnly");
  }
  document.querySelectorAll("[data-tag-key]").forEach((el) => keys.add("tags." + el.getAttribute("data-tag-key")));
  return keys;
}

function missingKeys(page, lang, document) {
  const keys = new Set(keysUsed(document));
  keys.add(`seo.${page.seo}.title`);
  keys.add(`seo.${page.seo}.description`);
  for (const ns of page.namespaces || []) leafKeys(lookup(dicts.en, ns), ns).forEach((k) => keys.add(k));
  return [...keys].filter((k) => typeof lookup(dicts[lang], k) !== "string");
}

// ---------- body translation (same rules as applyAll() in i18n.js) ----------

function applyRich(document, el, translated) {
  const frag = document.createDocumentFragment();
  const re = /\{(\w+)\}/g;
  let last = 0;
  let m;
  while ((m = re.exec(translated))) {
    if (m.index > last) frag.appendChild(document.createTextNode(translated.slice(last, m.index)));
    const token = el.querySelector(`[data-token="${m[1]}"]`);
    if (token) {
      if (token.getAttribute("data-i18n")) token.textContent = currentT(token.getAttribute("data-i18n"));
      frag.appendChild(token);
    }
    last = re.lastIndex;
  }
  if (last < translated.length) frag.appendChild(document.createTextNode(translated.slice(last)));
  el.textContent = "";
  el.appendChild(frag);
}

let currentT;
function translateBody(document, lang) {
  currentT = (key, vars) => t(lang, key, vars);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    if (el.closest("[data-i18n-rich]")) return;
    const value = currentT(el.getAttribute("data-i18n"));
    if (el.hasAttribute("data-i18n-placeholder")) {
      el.setAttribute("placeholder", value);
    } else if (el.hasAttribute("data-i18n-title")) {
      el.setAttribute("title", value);
      if (el.hasAttribute("aria-label")) el.setAttribute("aria-label", value);
    } else {
      el.textContent = value;
    }
  });

  document.querySelectorAll("[data-i18n-rich]").forEach((el) => applyRich(document, el, currentT(el.getAttribute("data-i18n-rich"))));

  document.querySelectorAll("[data-updated]").forEach((el) => {
    const out = el.querySelector(".gu-text");
    if (!out) return;
    const date = new Date(el.getAttribute("data-updated") + "T00:00:00Z");
    const shown = new Intl.DateTimeFormat(lang, { year: "numeric", month: "short", day: "numeric", timeZone: "UTC" }).format(date);
    const patch = el.getAttribute("data-patch");
    out.textContent = currentT(patch ? "shared.updated.withPatch" : "shared.updated.dateOnly", { patch, date: shown });
  });

  document.querySelectorAll("li .tags button[data-tag-key]").forEach((btn) => {
    btn.textContent = currentT("tags." + btn.getAttribute("data-tag-key"));
  });
}

// With <base href="../">, relative URLs resolve against the site root. Links that should
// stay inside this language (same-page anchors, and pages that have a copy in it) get the
// language folder put back in front.
function rewriteLinks(document, lang, file, published) {
  const isRelative = (h) => !/^([a-z][a-z0-9+.-]*:|\/)/i.test(h);
  document.querySelectorAll("a[href]").forEach((a) => {
    const href = a.getAttribute("href");
    if (!isRelative(href)) return;
    if (href.startsWith("#")) {
      a.setAttribute("href", langPath(lang, file) + href);
      return;
    }
    const m = href.match(/^(\.\/|[^?#/]+\.html)?([?#].*)?$/);
    if (!m) return;
    const target = !m[1] || m[1] === "./" ? "index.html" : m[1];
    if (published.has(`${lang}/${target}`)) a.setAttribute("href", langPath(lang, target) + (m[2] || ""));
  });
}

// ---------- head ----------

function alternatesBlock(page, langs) {
  const lines = [`<link rel="alternate" hreflang="en" href="${urlFor("en", page.file)}">`];
  for (const l of langs) lines.push(`<link rel="alternate" hreflang="${l}" href="${urlFor(l, page.file)}">`);
  lines.push(`<link rel="alternate" hreflang="x-default" href="${urlFor("en", page.file)}">`);
  return [ALT_START, ...lines, ALT_END].join("\n");
}

function setMeta(document, attr, name, content) {
  let el = document.querySelector(`meta[${attr}="${name}"]`);
  if (!el) {
    el = document.createElement("meta");
    el.setAttribute(attr, name);
    const anchor = document.querySelector('meta[property="og:url"]') || document.querySelector("title");
    anchor.after(el);
    anchor.after(document.createTextNode("\n"));
  }
  el.setAttribute("content", content);
}

function translateHead(document, page, lang, langs) {
  const html = document.documentElement;
  html.setAttribute("lang", lang);
  html.setAttribute("data-static-lang", lang);

  const head = document.head;
  const base = document.createElement("base");
  base.setAttribute("href", "../");
  head.prepend(base);

  const title = t(lang, `seo.${page.seo}.title`);
  const desc = t(lang, `seo.${page.seo}.description`);
  const url = urlFor(lang, page.file);

  document.querySelector("title").textContent = title;
  setMeta(document, "name", "description", desc);
  document.querySelector('link[rel="canonical"]').setAttribute("href", url);
  setMeta(document, "property", "og:url", url);
  setMeta(document, "property", "og:title", title);
  setMeta(document, "property", "og:description", desc);
  setMeta(document, "property", "og:locale", OG_LOCALE[lang]);
  if (document.querySelector('meta[name="twitter:title"]')) setMeta(document, "name", "twitter:title", title);
  if (document.querySelector('meta[name="twitter:description"]')) setMeta(document, "name", "twitter:description", desc);

  document.querySelectorAll('script[type="application/ld+json"]').forEach((s) => {
    s.textContent = s.textContent.replace(/"inLanguage":\s*"en"/g, `"inLanguage": "${lang}"`);
  });
}

// ---------- English source pages: a marker block of hreflang links after the canonical ----------

function withAlternates(source, page, langs) {
  const stripped = source.replace(new RegExp(`\\n?${escapeRe(ALT_START)}[\\s\\S]*?${escapeRe(ALT_END)}`), "");
  if (!langs.length) return stripped;
  const canon = stripped.match(/<link rel="canonical"[^>]*>/);
  if (!canon) throw new Error(`${page.file}: no <link rel="canonical"> to anchor the hreflang block`);
  const block = alternatesBlock(page, langs);
  return stripped.replace(canon[0], `${canon[0]}\n${block}`);
}
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

// ---------- sitemap ----------

function withSitemapAlternates(xml, clusters) {
  xml = xml.replace(new RegExp(`\\s*${escapeRe(MAP_START)}[\\s\\S]*?${escapeRe(MAP_END)}`), "");
  xml = xml.replace(/\n\s*<xhtml:link [^>]*\/>/g, "");
  if (!xml.includes("xmlns:xhtml")) {
    xml = xml.replace('<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
      '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">');
  }
  const extra = [];
  for (const { page, langs } of clusters) {
    if (!langs.length) continue;
    const links = ["en", ...langs, "x-default"].map((l) =>
      `    <xhtml:link rel="alternate" hreflang="${l}" href="${urlFor(l === "x-default" ? "en" : l, page.file)}"/>`).join("\n");
    const enLoc = `<loc>${urlFor("en", page.file)}</loc>`;
    const entry = xml.match(new RegExp(`<url>\\s*${escapeRe(enLoc)}[\\s\\S]*?</url>`));
    if (!entry) throw new Error(`sitemap.xml has no entry for ${urlFor("en", page.file)}`);
    const lastmod = (entry[0].match(/<lastmod>[^<]*<\/lastmod>/) || [""])[0];
    xml = xml.replace(entry[0], entry[0].replace(/\s*<\/url>$/, `\n${links}\n  </url>`));
    for (const l of langs) {
      extra.push(`  <url>\n    <loc>${urlFor(l, page.file)}</loc>\n${lastmod ? `    ${lastmod}\n` : ""}${links}\n  </url>`);
    }
  }
  if (extra.length) xml = xml.replace("</urlset>", `  ${MAP_START}\n${extra.join("\n")}\n  ${MAP_END}\n</urlset>`);
  return xml;
}

// ---------- build ----------

const outputs = new Map(); // relative path -> contents
const clusters = [];
const skipped = [];

// First pass: decide which language copies are published, so links can target them.
for (const page of PAGES) {
  const { document } = parseHTML(read(page.file));
  const langs = page.langs.filter((lang) => {
    const missing = missingKeys(page, lang, document);
    if (missing.length) skipped.push(`${lang}/${page.file}: ${missing.length} missing key(s), e.g. ${missing.slice(0, 3).join(", ")}`);
    return !missing.length;
  });
  clusters.push({ page, langs });
}
const published = new Set(clusters.flatMap(({ page, langs }) => langs.map((l) => `${l}/${page.file}`)));

for (const { page, langs } of clusters) {
  const source = withAlternates(read(page.file), page, langs);
  outputs.set(page.file, source);
  for (const lang of langs) {
    const { document } = parseHTML(source);
    translateHead(document, page, lang, langs);
    translateBody(document, lang);
    rewriteLinks(document, lang, page.file, published);
    const banner = `<!-- Generated by scripts/i18n-build.mjs from ${page.file}. Do not edit; run pnpm i18n. -->`;
    const html = document.toString().replace(/^(<!doctype html>)/i, `$1\n${banner}`);
    outputs.set(`${lang}/${page.file}`, html.endsWith("\n") ? html : html + "\n");
  }
}
outputs.set("sitemap.xml", withSitemapAlternates(read("sitemap.xml"), clusters));

// Generated folders hold nothing but build output, so anything not rebuilt is stale.
const stale = LANGS.flatMap((l) => {
  const dir = path.join(ROOT, l);
  return fs.existsSync(dir) ? fs.readdirSync(dir).map((f) => `${l}/${f}`).filter((p) => !outputs.has(p)) : [];
});

for (const s of skipped) console.warn(`skipped ${s}`);

if (check) {
  const differ = [...outputs].filter(([p, c]) => !fs.existsSync(path.join(ROOT, p)) || read(p) !== c).map(([p]) => p);
  differ.push(...stale);
  if (differ.length) {
    console.error(`Translated pages are out of date. Run pnpm i18n and commit:\n  ${differ.join("\n  ")}`);
    process.exit(1);
  }
  console.log("Translated pages are up to date.");
} else {
  for (const p of stale) fs.rmSync(path.join(ROOT, p));
  for (const [p, c] of outputs) {
    const full = path.join(ROOT, p);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    if (!fs.existsSync(full) || fs.readFileSync(full, "utf8") !== c) fs.writeFileSync(full, c);
  }
  console.log(`Wrote ${published.size} translated page(s): ${[...published].sort().join(", ") || "none"}`);
}
